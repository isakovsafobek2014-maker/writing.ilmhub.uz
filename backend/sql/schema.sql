-- 1. Tizim foydalanuvchilari jadvali
CREATE TABLE IF NOT EXISTS users (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    username VARCHAR(50) UNIQUE NOT NULL,
    password VARCHAR(100) NOT NULL,
    role VARCHAR(20) CHECK (role IN ('Developer', 'Director', 'Admin', 'Teacher', 'Student', 'Guest')) NOT NULL,
    stage VARCHAR(50) DEFAULT 'Kids',
    group_name VARCHAR(100),
    xp INTEGER DEFAULT 0,
    is_banned BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Existing installations need these columns/tables too.
ALTER TABLE users ADD COLUMN IF NOT EXISTS group_name VARCHAR(100);

CREATE TABLE IF NOT EXISTS content_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_type VARCHAR(50) NOT NULL CHECK (module_type IN ('reading', 'listening', 'vocabulary', 'speaking', 'writing')),
    level VARCHAR(10) NOT NULL DEFAULT 'B1',
    data JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id TEXT,
    sender_name TEXT NOT NULL,
    sender_role TEXT NOT NULL,
    channel TEXT NOT NULL CHECK (channel IN ('staff', 'student')),
    group_name TEXT,
    content TEXT,
    audio_url TEXT,
    video_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

